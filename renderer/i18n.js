let currentLang = 'en';

function t(key, opts) {
  const lang = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  const en   = TRANSLATIONS.en;

  if (opts && opts.count !== undefined) {
    const n = opts.count;
    const pluralKey = key + (n === 1 ? '_one' : '_other');
    const str = lang[pluralKey] || en[pluralKey] || key;
    return str.replace('{n}', n);
  }

  let str = lang[key] || en[key] || key;

  if (opts && Array.isArray(opts.args)) {
    opts.args.forEach((v, i) => { str = str.replace('{' + i + '}', v); });
  }
  return str;
}

function applyAll() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key  = el.dataset.i18n;
    const prop = el.dataset.i18nProp;
    if (prop === 'placeholder') el.placeholder = t(key);
    else el.textContent = t(key);
  });
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  applyAll();
  if (typeof renderJobs === 'function') renderJobs();
  if (typeof updateStatusBar === 'function') updateStatusBar();
}
