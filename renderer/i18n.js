// Looks up a hint's translation for the current language; anything without one
// (including all of English) is shown as written.
function tHint(text) {
  if (!text || currentLang === 'en') return text;
  const map = HINT_TRANSLATIONS[currentLang];
  if (!map) return text;
  if (map[text]) return map[text];
  for (const k in map) {
    if (k.endsWith(': ') && text.startsWith(k)) return map[k] + text.slice(k.length);
  }
  return text;
}
